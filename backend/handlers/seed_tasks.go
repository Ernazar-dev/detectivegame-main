func SeedTasks(db *gorm.DB) error {
	var teacher models.User
	if err := db.Where("role = ?", "teacher").First(&teacher).Error; err != nil {
		return nil
	}
	var existing int64
	db.Model(&models.Task{}).Count(&existing)
	if existing > 0 {
		return nil
	}

	tasks := defaultSeedTasks()
	for _, st := range tasks {
		t := models.Task{
			Title:              st.Title,
			Difficulty:         st.Difficulty,
			Scenario:           st.Scenario,
			TimerMinutes:       st.TimerMinutes,
			CorrectReasoning:   strPtr(st.CorrectReasoning),
			EvidenceReferences: strPtr(st.EvidenceReferences),
			LocationAssetID:    strPtr(st.LocationKey),
			AssignedToAll:      true,
			CreatedBy:          teacher.ID,
			Status:             "published",
		}
		if err := db.Create(&t).Error; err != nil {
			return err
		}

		for i, sc := range st.Scenes {
			scene := models.Scene{
				TaskID:         t.ID,
				Order:          i + 1,
				Title:          sc.Title,
				Body:           sc.Body,
				ImageAsset:     strPtr(sc.ImageAsset),
				CharacterAsset: strPtr(sc.CharacterAsset),
			}
			db.Create(&scene)
		}

		var culpritID *uint
		for _, ss := range st.Suspects {
			s := models.Suspect{
				TaskID:           t.ID,
				CharacterAssetID: strPtr(ss.CharacterKey),
				SuspectStatus:    "suspect",
				Name:             ss.Name,
				Avatar:           strPtr(ss.CharacterKey),
				Role:             ss.Role,
				Description:      ss.Description,
				BehaviorTraits:   ss.BehaviorTraits,
				SecretAlibi:      strPtr(ss.SecretAlibi),
			}
			db.Create(&s)
			if ss.IsCulprit {
				culpritID = uPtr(s.ID)
			}
			for _, q := range ss.Questions {
				db.Create(&models.Question{SuspectID: s.ID, Question: q.Q, Answer: q.A})
			}
			for _, e := range ss.Evidence {
				db.Create(&models.Evidence{
					TaskID:    t.ID,
					SuspectID: s.ID,
					Kind:      e.Kind,
					FileName:  e.FileName,
					Title:     e.Title,
					Body:      e.Body,
					Hint:      e.Hint,
					Locked:    e.Locked,
					Password:  e.Password,
					Relevance: e.Relevance,
					Command:   e.Command,
					SortOrder: e.Order,
				})
			}
		}
		if culpritID != nil {
			db.Model(&t).Update("correct_suspect_id", *culpritID)
		}
	}
	return nil
}